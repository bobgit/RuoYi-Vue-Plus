三、未来扩展性分析（按业务维度）

下面分析不同业务引入后你的结构是否支持。

1）外卖扩展

外卖核心关键字段：

配送范围

起送价

配送费

配送时间

商家地点

✔ 商品体系：适配
✔ SKU 库存：适配 daily_limit 和 infinite 模式
✔ 订单：需增加配送字段（extend_json）
✔ 活动：OK

→ 可支持

2）旅游 & 门票

门票关键：

有效期

验证方式（二维码）

一票多用

是否实名

→ 建议全部放 extend_json 中
→ SKU infinite 库存模式

→ 你的设计完全能支持

3）吃喝玩乐（服务券、代金券）

服务型商品往往：

无库存

需要预约时间

可退款规则不同

→ 你的结构完全能支持
→ 订单需要 extend_json

4）秒杀

秒杀需要：

活动库存

秒杀价格

限购

高并发库存扣减

你的 activity + activity_product 正好完美支持秒杀：

秒杀商品=一种特殊 activity

秒杀价 = activity_product.group_price

秒杀库存 = stock_quantity

限购 = limit_per_user

唯一需要加强：

秒杀库存扣减必须使用 PostgreSQL 行级锁或函数

推荐使用：

UPDATE gmt_activity_product
SET stock_quantity = stock_quantity - 1
WHERE activity_product_id = ?
AND stock_quantity > 0;
