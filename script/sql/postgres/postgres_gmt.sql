DROP TABLE sys_task_record;
CREATE TABLE sys_task_record (
    -- 主键ID，会自动创建一个序列并设置默认值，是 PostgreSQL 的标准做法。
    id INT8 GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    task_type   varchar(10)  default 'mail'::varchar,
    -- 存储任务数据，最大长度为255字符。
    data VARCHAR(255),
    -- 任务状态，不允许为空，默认值为 'PENDING'。
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    -- 错误信息，使用 TEXT 类型以存储可变长度的长文本。
    error_msg TEXT,
    -- 重试次数，默认为 0。
    -- 使用 INTEGER 而非 INT 是更明确的写法，但两者在PG中均可。
    retry_count INTEGER DEFAULT 0,
    tenant_id          varchar(20)      default '000000'::varchar,
    create_dept        int8,
    -- 记录创建时间，默认值为当前时间戳。
    -- NOW() 和 CURRENT_TIMESTAMP 在此场景下功能相同。
    create_by          int8,
    create_time        timestamp DEFAULT NOW(),
    -- 记录更新时间，默认值为当前时间戳。
    -- 注意：此字段的自动更新功能由下面的触发器实现。
    update_by          int8,
    update_time        timestamp DEFAULT NOW(),
    del_flag           char             default '0'::bpchar
);

